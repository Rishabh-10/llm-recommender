import os
from pathlib import Path

import streamlit as st
from dotenv import load_dotenv
from google import genai

APP_NAME = "PickWise"
MODEL = "gemini-3.5-flash"
FREE_MODEL = "gemini-3.5-flash-lite"

# The app owner's key for the free fallback: .local.env locally, App Secrets on Community Cloud.
# It stays on the server and is never shown to visitors.
load_dotenv(Path(__file__).parent / ".local.env")
FREE_KEY = os.getenv("GEMINI_API_KEY")

CATEGORIES = {
    "Anime": "🎌",
    "Movies": "🎬",
    "Books": "📚",
    "TV Shows": "📺",
    "Video Games": "🎮",
    "Music": "🎵",
}


def build_prompt(category: str, likes: str, mood: str, count: int) -> str:
    prompt = f"Recommend {count} {category.lower()} for me.\n"
    if likes:
        prompt += f"Things I already like: {likes}. Don't recommend any of these.\n"
    if mood:
        prompt += f"I'm in the mood for: {mood}.\n"
    prompt += (
        "Format the answer as a numbered Markdown list. For each item give the "
        "**title** in bold, the release year in parentheses, and one or two "
        "sentences on why I'd enjoy it. No intro or outro text."
    )
    return prompt


st.set_page_config(page_title=APP_NAME, page_icon="✨")
st.title(f"✨ {APP_NAME}")
st.caption("Tell me what you like and I'll find your next favorite thing.")

with st.sidebar:
    st.header("🔑 Gemini API key")
    # Masked input; the key lives only in this browser session and is never saved
    api_key = st.text_input("API key", type="password", placeholder="Paste your key")
    if FREE_KEY:
        st.caption(f"Optional. Leave empty to use the free model ({FREE_MODEL}).")
    st.caption("Get one at [Google AI Studio](https://aistudio.google.com/apikey).")

category = st.selectbox(
    "What do you want recommendations for?",
    list(CATEGORIES),
    format_func=lambda c: f"{CATEGORIES[c]} {c}",
)
likes = st.text_input(
    "What have you enjoyed before? (optional)",
    placeholder="e.g. Fullmetal Alchemist, Death Note",
)
mood = st.text_input(
    "Any genre or mood? (optional)",
    placeholder="e.g. dark fantasy, feel-good, mind-bending",
)
count = st.slider("How many recommendations?", 1, 10, 5)

if api_key:
    key, model = api_key.strip(), MODEL
else:
    key, model = FREE_KEY, FREE_MODEL

if st.button("Recommend", type="primary", disabled=not key):
    with st.spinner(f"Finding {category.lower()} for you..."):
        try:
            # A fresh client per request, so one visitor's key is never shared with another
            client = genai.Client(api_key=key)
            response = client.models.generate_content(
                model=model,
                contents=build_prompt(category, likes, mood, count),
            )
        except Exception:
            if api_key:
                st.error("Couldn't get recommendations. Check that your API key is valid.")
            else:
                st.error(
                    "The free model is busy or out of quota right now. "
                    "Try again in a minute, or add your own API key in the sidebar."
                )
        else:
            st.subheader(f"{CATEGORIES[category]} Your {category} picks")
            st.markdown(response.text)
            st.caption(f"Generated by {model}")
